test('fill, insert, send and copy act at once on a template without variables', SLOW, async ($, on) => {
  const f = setup($, on)
  const ui = await f.mount('desktop')
  await ui.press({ key: 'fill:2' })
  await ui.press({ key: 'insert:2' })
  await ui.press({ key: 'send:3' })
  await ui.press({ key: 'copy:2' })
  expect(f.filled).toEqual([{ text: 'Write a short mail', mode: 'replace' }, { text: 'Write a short mail', mode: 'insert' }])
  expect(f.sent).toEqual(['Ship it'])
  expect(f.copied()).toBe('Write a short mail')
})

test('a template with variables opens a form; the chosen action uses the filled text and values are remembered', SLOW, async ($, on) => {
  const f = setup($, on)
  for (const surface of SURFACES) {
    f.filled.length = 0
    const ui = await f.mount(surface)
    await ui.press({ key: 'insert:1' })
    await ui.redraw()
    expect(f.filled).toEqual([])
    await ui.input({ key: 'var:file', text: 'app.ts', kind: 'change' })
    await ui.input({ key: 'var:topic', text: 'bugs', kind: 'change' })
    await ui.redraw()
    await ui.press({ key: 'vars-insert' })
    await ui.redraw()
    expect(f.filled).toEqual([{ text: 'Review app.ts for bugs', mode: 'insert' }])
    expect(await ui.find({ key: 'search' })).toBeDefined()
    expect(f.store.lastVars).toEqual({ file: 'app.ts', topic: 'bugs' })
    await ui.press({ key: 'send:1' })
    await ui.redraw()
    expect((await ui.find({ key: 'var:file' }))?.props.value).toBe('app.ts')
    await ui.press({ key: 'vars-cancel' })
    await ui.redraw()
    expect(f.sent).toEqual([])
    await ui.unmount()
  }
})

test('/prompts opens the pane; /prompts <name> fills that template or opens its form', SLOW, async ($, on) => {
  const f = setup($, on)
  const ui = await f.mount('desktop')
  const opened = await $.command.run({ command: 'prompts' } as any)
  expect(f.opened()).toBe(1)
  expect(opened.text).toMatch(/opened/i)
  const filled = await $.command.run({ command: 'prompts', args: 'mai' } as any)
  expect(f.filled).toEqual([{ text: 'Write a short mail', mode: 'replace' }])
  expect(filled.text).toMatch(/Mail/)
  const form = await $.command.run({ command: 'prompts', args: 'review' } as any)
  expect(form.text).toMatch(/variables/i)
  await ui.redraw()
  expect(await ui.find({ key: 'var:topic' })).toBeDefined()
  const missing = await $.command.run({ command: 'prompts', args: 'nope' } as any)
  expect(missing.text).toMatch(/No template/)
})

test('delete asks first and removes only after confirmation', SLOW, async ($, on) => {
  const f = setup($, on)
  const ui = await f.mount('terminal')
  await ui.press({ key: 'delete:2' })
  await ui.redraw()
  await ui.press({ key: 'delete-cancel' })
  await ui.redraw()
  expect((f.store.templates as any[]).length).toBe(3)
  await ui.press({ key: 'delete:2' })
  await ui.redraw()
  await ui.press({ key: 'delete-confirm' })
  await ui.redraw()
  expect((f.store.templates as any[]).map(t => t.name)).toEqual(['Review', 'Deploy'])
  expect(await ui.find({ key: 'fill:2' })).toBeUndefined()
})

test('export writes every template; import replaces or skips same names and reports bad files', SLOW, async ($, on) => {
  const f = setup($, on)
  const ui = await f.mount('desktop')
  await ui.press({ key: 'io' })
  await ui.redraw()
  expect((await ui.find({ key: 'io-path' }))?.props.value).toBe('C:/Users/me/prompt-templates.json')
  await ui.press({ key: 'io-export' })
  expect(JSON.parse(f.files['C:/Users/me/prompt-templates.json']!).templates.map((t: any) => t.name)).toEqual(['Deploy', 'Mail', 'Review'])
  await ui.input({ key: 'io-path', text: 'C:/in.json', kind: 'change' })
  await ui.press({ key: 'io-import-skip' })
  await ui.redraw()
  expect((f.store.templates as any[]).find(t => t.name === 'Mail').body).toBe('Write a short mail')
  expect(await ui.find({ type: 'Text', text: /1 added.*1 skipped/ })).toBeDefined()
  await ui.press({ key: 'io-import-replace' })
  await ui.redraw()
  expect((f.store.templates as any[]).find(t => t.name.toLowerCase() === 'mail').body).toBe('NEW')
  expect((f.store.templates as any[]).filter(t => t.name === 'Extra')).toHaveLength(1)
  await ui.input({ key: 'io-path', text: 'C:/missing.json', kind: 'change' })
  await ui.press({ key: 'io-import-skip' })
  await ui.redraw()
  expect(await ui.find({ type: 'Text', text: /could not be read/i })).toBeDefined()
})
