import { expect, test } from 'claude-code/testing'

import { SLOW, SURFACES, setup } from './fixture'

test('the list shows every template sorted by name, search and tag chips filter it', SLOW, async ($, on) => {
  const f = setup($, on)
  for (const surface of SURFACES) {
    f.filled.length = 0
    const ui = await f.mount(surface)
    expect((await ui.findAll({ type: 'Text', text: /^(Deploy|Mail|Review)$/ })).map((x: any) => x.text)).toEqual(['Deploy', 'Mail', 'Review'])
    await ui.input({ key: 'search', text: 'mail', kind: 'change' })
    await ui.redraw()
    expect(await ui.find({ key: 'fill:2' })).toBeDefined()
    expect(await ui.find({ key: 'fill:1' })).toBeUndefined()
    await ui.input({ key: 'search', text: '', kind: 'change' })
    await ui.press({ key: 'tag:ops' })
    await ui.redraw()
    expect(await ui.find({ key: 'fill:3' })).toBeDefined()
    expect(await ui.find({ key: 'fill:2' })).toBeUndefined()
    await ui.press({ key: 'tag:ops' })
    await ui.redraw()
    expect(await ui.find({ key: 'fill:2' })).toBeDefined()
    await ui.unmount()
  }
})

